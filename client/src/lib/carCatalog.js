export const MAKES = Object.keys(CAR_CATALOG).sort((a, b) => a.localeCompare(b, "ru"));

export function matchMake(raw) {
  if (!raw) return "";
  const trimmed = raw.trim();
  const found = MAKES.find((m) => m.toLowerCase() === trimmed.toLowerCase());
  return found || titleCase(trimmed);
}

export function matchModel(make, raw) {
  if (!raw) return "";
  const trimmed = raw.trim();
  const options = CAR_CATALOG[make];
  if (!options) return trimmed;
  const found = options.find((m) => m.toLowerCase() === trimmed.toLowerCase());
  return found || trimmed;
}

export function titleCase(s) {
  return s.replace(/\S+/g, (w) => w[0].toUpperCase() + w.slice(1).toLowerCase());
}
